/** Looks up a string; `{name}` placeholders are filled from `vars`. */
export function t(
  key: keyof typeof en,
  vars?: Record<string, string | number>,
): string {
  const text: string = en[key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
